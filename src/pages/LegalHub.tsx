type Template = { name: string; promptName: string; description: string; status: string };

/** A real starter draft — headings and signature blocks a founder fills in. */
function downloadTemplate(template: Template) {
 const lines = [
  `# ${template.promptName}`,
  '',
  '_Starter draft generated by CoFounderBay Legal Hub — replace every bracketed item and have counsel review before signing._',
  '',
  '## Parties',
  '- Company: [Company legal name], a [State] [entity type]',
  '- Counterparty: [Name], [address]',
  '',
  '## Effective Date',
  '[Date]',
  '',
  '## Key Terms',
  '1. [Term one]',
  '2. [Term two]',
  '3. [Term three]',
  '',
  '## Signatures',
  '- Company: ____________________  Date: ________',
  '- Counterparty: ____________________  Date: ________',
 ];
 const blob = new Blob([lines.join('\n')], { type: 'text/markdown;charset=utf-8' });
 const url = URL.createObjectURL(blob);
 const anchor = document.createElement('a');
 anchor.href = url;
 anchor.download = `${template.promptName.replace(/[^a-z0-9]+/gi, '-').toLowerCase()}-draft.md`;
 anchor.click();
 URL.revokeObjectURL(url);
}

