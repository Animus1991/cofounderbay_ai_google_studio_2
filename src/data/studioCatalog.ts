export function createAvatarSvg(initials: string, bgStart: string, bgEnd: string, accent: string): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 120 120" width="120" height="120">
    <defs>
      <linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%">
        <stop offset="0%" stop-color="${bgStart}" />
        <stop offset="100%" stop-color="${bgEnd}" />
      </linearGradient>
    </defs>
    <rect width="120" height="120" rx="28" fill="url(#g)" />
    <circle cx="96" cy="24" r="34" fill="${accent}" fill-opacity="0.18" />
    <circle cx="20" cy="100" r="28" fill="${accent}" fill-opacity="0.14" />
    <text x="50%" y="54%" dominant-baseline="middle" text-anchor="middle" fill="#FFFFFF" font-family="Plus Jakarta Sans, Inter, system-ui, sans-serif" font-weight="700" font-size="40" letter-spacing="-1">${initials}</text>
  </svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

