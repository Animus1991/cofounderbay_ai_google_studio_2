const TAXONOMY: Record<string, string> = Object.fromEntries([
  ...STAGES.map((term) => [term.value, term.el]),
  ...COMMITMENTS.map((term) => [term.value, term.el]),
  ...PERSON_ROLES.map((term) => [term.value, term.el]),
  ...INDUSTRIES.map((term) => [term.value, term.el]),
  ...ALL_SKILLS.map((term) => [term.value, term.el]),
]);

/** The active language only. */
export function bothText(en: string, el: string): string {
  return getLang() === 'el' ? el : en;
}

function lookup(value: string): string | undefined {
  if (EL[value]) return EL[value];
  if (TAXONOMY[value]) return TAXONOMY[value];
  const lower = value.toLowerCase();
  const key = Object.keys(EL).find((item) => item.toLowerCase() === lower);
  if (key) return EL[key];
  const tax = Object.keys(TAXONOMY).find((item) => item.toLowerCase() === lower);
  return tax ? TAXONOMY[tax] : undefined;
}

/** Translate a known label. An unknown key, including a tenant name, stays as it is. */
export function withEl(en: string): string {
  const el = lookup(en);
  if (!el) return en;
  return bothText(en, el);
}

/** A stored English value in the active language. Greek lookup ignores case (`MEETUP` → «Συνάντηση»). */
export function labelOf(value: string | null | undefined): string {
  if (!value) return '';
  if (getLang() !== 'el') return value;
  return lookup(value) || value;
}
